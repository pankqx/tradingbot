"use client";

import Link from "next/link";
import { useCallback, useEffect, useRef, useState, useSyncExternalStore } from "react";
import { Bell, Database, Search } from "lucide-react";
import { CommandPalette, type PaletteInstrument } from "./command-palette";
import { Logo } from "./ui";
import { ThemeToggle } from "./theme";
import { useDismiss } from "./use-dismiss";

export interface Notice { id: string; text: string; sub: string; href: string; tone: "up" | "down" | "warn" }

/* ── Market session (NSE cash market, Mon–Fri 09:15–15:30 IST; exchange holidays are not loaded) ── */
function istNow(): { day: number; minutes: number; label: string } {
  const parts = new Intl.DateTimeFormat("en-GB", { timeZone: "Asia/Kolkata", weekday: "short", hour: "2-digit", minute: "2-digit", hour12: false }).formatToParts(new Date());
  const get = (t: string) => parts.find((p) => p.type === t)!.value;
  const day = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"].indexOf(get("weekday"));
  const h = Number(get("hour")) % 24, m = Number(get("minute"));
  return { day, minutes: h * 60 + m, label: `${String(h).padStart(2, "0")}:${String(m).padStart(2, "0")}` };
}
const clockSubscribe = (cb: () => void) => { const t = setInterval(cb, 15000); return () => clearInterval(t); };
const clockSnapshot = () => istNow().label + "|" + istNow().day + "|" + istNow().minutes;

function MarketStatus() {
  const snap = useSyncExternalStore(clockSubscribe, clockSnapshot, () => "");
  if (!snap) return <span className="h-7 w-32 rounded-full bg-line/60" aria-hidden />;
  const [label, d, mins] = snap.split("|");
  const day = Number(d), min = Number(mins);
  const weekday = day >= 1 && day <= 5;
  const state = !weekday ? "Closed · weekend" : min >= 555 && min < 930 ? "Market open" : min >= 540 && min < 555 ? "Pre-open" : "Market closed";
  const open = state === "Market open";
  return (
    <span className="hidden items-center gap-2 rounded-full border border-line bg-surface px-3 py-1 text-[12.5px] text-ink-2 sm:inline-flex" title="NSE cash market 09:15–15:30 IST. Exchange holidays are not loaded in this demo.">
      <span className={`size-2 rounded-full ${open ? "live-dot bg-up" : "bg-ink-3"}`} />
      {state}
      <span className="num text-ink-3">{label} IST</span>
    </span>
  );
}

export function Header({ instruments, notices, asOfLabel }: { instruments: PaletteInstrument[]; notices: Notice[]; asOfLabel: string }) {
  const [palette, setPalette] = useState(false);
  const [bell, setBell] = useState(false);
  const [profile, setProfile] = useState(false);
  const [seen, setSeen] = useState(false);
  const bellRef = useRef<HTMLDivElement>(null);
  const profRef = useRef<HTMLDivElement>(null);
  const closeBell = useCallback(() => setBell(false), []);
  const closeProfile = useCallback(() => setProfile(false), []);
  useDismiss(bellRef, bell, closeBell);
  useDismiss(profRef, profile, closeProfile);

  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      const el = e.target as HTMLElement;
      const typing = el.tagName === "INPUT" || el.tagName === "TEXTAREA" || el.isContentEditable;
      if ((e.metaKey || e.ctrlKey) && e.key.toLowerCase() === "k") { e.preventDefault(); setPalette((p) => !p); }
      else if (e.key === "/" && !typing) { e.preventDefault(); setPalette(true); }
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, []);

  return (
    <header className="sticky top-0 z-20 flex h-14 items-center gap-3 border-b border-line bg-paper/85 px-4 backdrop-blur-md lg:px-8">
      <Link href="/" className="text-ink md:hidden" aria-label="tradingb0t home"><Logo size={24} /></Link>
      <button onClick={() => setPalette(true)} className="group flex h-9 min-w-0 flex-1 items-center gap-2.5 rounded-lg border border-line bg-surface px-3 text-left text-[13.5px] text-ink-3 transition-colors hover:border-line-strong md:max-w-[400px]" aria-label="Search instruments">
        <Search className="size-4 shrink-0" strokeWidth={1.8} />
        <span className="flex-1 truncate">Search stocks, sectors, pages</span>
        <kbd className="hidden rounded border border-line px-1.5 py-0.5 text-[11px] sm:block">⌘K</kbd>
      </button>
      <div className="ml-auto flex items-center gap-2">
        <MarketStatus />
        <Link href="/methodology#data" className="hidden items-center gap-1.5 rounded-full border border-warn/40 bg-warn-soft px-3 py-1 text-[12.5px] font-medium text-warn xl:inline-flex" title="All prices are generated by a deterministic simulator. Click to see how.">
          <Database className="size-3.5" strokeWidth={1.8} />
          Simulated data · {asOfLabel}
        </Link>
        <ThemeToggle />
        <div ref={bellRef} className="relative">
          <button onClick={() => { setBell((b) => !b); setSeen(true); setProfile(false); }} aria-label="Notifications" aria-expanded={bell} className="relative grid size-9 place-items-center rounded-full text-ink-2 hover:bg-line/60">
            <Bell className="size-[17px]" strokeWidth={1.7} />
            {!seen && notices.length > 0 && <span className="absolute right-2 top-2 size-2 rounded-full border-2 border-paper bg-accent" />}
          </button>
          {bell && (
            <div className="menu-pop absolute right-0 top-11 w-[340px] max-w-[calc(100vw-2rem)] overflow-hidden rounded-xl border border-line-strong bg-raised shadow-[var(--shadow)]">
              <div className="border-b border-line px-4 py-2.5 text-[13px] font-semibold">Recent signal activity</div>
              {notices.length === 0 ? <p className="px-4 py-8 text-center text-[13px] text-ink-2">No new signals or invalidations in the last 5 bars.</p> : (
                <ul className="max-h-[360px] divide-y divide-line overflow-y-auto">
                  {notices.map((n) => (
                    <li key={n.id}><Link href={n.href} onClick={() => setBell(false)} className="row-hover flex gap-3 px-4 py-2.5">
                      <span className={`mt-1.5 size-2 shrink-0 rounded-full ${n.tone === "up" ? "bg-up" : n.tone === "down" ? "bg-down" : "bg-warn"}`} />
                      <span><span className="block text-[13.5px]">{n.text}</span><span className="block text-[12.5px] text-ink-3">{n.sub}</span></span>
                    </Link></li>
                  ))}
                </ul>
              )}
            </div>
          )}
        </div>
        <div ref={profRef} className="relative">
          <button onClick={() => { setProfile((p) => !p); setBell(false); }} aria-label="Account" aria-expanded={profile} className="grid size-8 place-items-center rounded-full bg-ink text-[12px] font-semibold text-paper">D</button>
          {profile && (
            <div className="menu-pop absolute right-0 top-11 w-[260px] rounded-xl border border-line-strong bg-raised p-1.5 shadow-[var(--shadow)]">
              <div className="px-3 py-2.5"><p className="text-[13.5px] font-medium">Demo account</p><p className="text-[12.5px] text-ink-3">Sign-in and onboarding arrive in the next milestone.</p></div>
              <Link href="/roadmap/settings" onClick={() => setProfile(false)} className="row-hover block rounded-md px-3 py-2 text-[13.5px]">Preferences (coming soon)</Link>
              <Link href="/methodology" onClick={() => setProfile(false)} className="row-hover block rounded-md px-3 py-2 text-[13.5px]">How signals work</Link>
            </div>
          )}
        </div>
      </div>
      <CommandPalette open={palette} onClose={() => setPalette(false)} instruments={instruments} />
    </header>
  );
}
